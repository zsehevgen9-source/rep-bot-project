"""Общие проверки текста заданий (без внешних зависимостей)."""
import re

# Признаки того, что задание требует картинку/чертёж, которых в чате нет
_PICTURE_PATTERNS = [
    r"рисун", r"\bрис\.", r"изображ", r"изобраз", r"картинк", r"фотограф", r"\bфото\b",
    r"на\s+(схеме|графике|карте|диаграмме|иллюстрации|чертеже|снимке)",
    r"(по|на|в)\s+(схеме|графику|графике|карте|диаграмме|таблице)\s+(ниже|выше|справа|слева)",
    r"приведённ\w*\s+(схем|график|карт|диаграмм|таблиц)", r"приведенн\w*\s+(схем|график|карт|диаграмм|таблиц)",
    r"нарисуй", r"нарисуйте", r"начерт", r"постройте\s+график", r"построй\s+график",
]


def needs_picture(text: str) -> bool:
    """True, если задание ссылается на рисунок/схему/график или просит что-то нарисовать."""
    low = text.lower()
    return any(re.search(p, low) for p in _PICTURE_PATTERNS)


