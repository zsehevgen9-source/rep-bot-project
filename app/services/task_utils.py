def normalize_answer(value: str) -> str:
    """Ответ без пробелов, регистра, «ё» и с точкой вместо запятой — для сравнения с эталоном."""
    return re.sub(r"\s+", "", str(value).lower().replace("ё", "е").replace(",", ".")).strip(".")


def parse_options(value) -> list:
    """Варианты ответа: список или строка «a | b | c»."""
    if isinstance(value, list):
        items = value
    else:
        items = str(value or "").split("|")
    return [str(i).strip() for i in items if str(i).strip()]
