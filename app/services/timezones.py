def zone_name(offset_minutes: Optional[int]) -> str:
    """«Екатеринбург (UTC+5)» по смещению в минутах."""
    hours = (offset_minutes if offset_minutes is not None else 300) // 60
    city = next((c for h, c in ZONES if h == hours), None)
    sign = "+" if hours >= 0 else "−"
    label = f"UTC{sign}{abs(hours)}"
    return f"{city} ({label})" if city else label


def detect_city(text: str) -> Optional[int]:
    """Смещение в минутах по названию города или региона (или None, если не узнали)."""
    words = re.sub(r"[^\wё\- ]", " ", (text or "").lower()).split()
    if not words:
        return None
    phrase = " ".join(words)
    words = words + [part for w in words if "-" in w for part in w.split("-") if part]   # «санкт-петербург»
    best: Optional[Tuple[int, int]] = None   # (длина совпадения, часы)
    for hours, stems in _CITY_STEMS.items():
        for stem in stems:
            if stem.startswith("="):                     # короткое название — только целым словом
                found = stem[1:] in words
            elif " " in stem or "-" in stem:
                found = stem in phrase
            else:
                found = any(w.startswith(stem) for w in words)
            if found and (best is None or len(stem) > best[0]):
                best = (len(stem), hours)
    return best[1] * 60 if best else None


def detect_time(text: str, now_utc_hour: int, now_utc_minute: int) -> Optional[int]:
    """Ученик написал, сколько у него времени («14:58», «15 ч»): смещение в минутах до ближайшего часа."""
    m = re.search(r"\b([01]?\d|2[0-3])(?:[:.](\d{2}))?\b", text or "")
    if not m:
        return None
    local = int(m.group(1)) * 60 + int(m.group(2) or 0)
    utc = now_utc_hour * 60 + now_utc_minute
    diff = (local - utc) % (24 * 60)
    if diff > 14 * 60:
        diff -= 24 * 60
    hours = round(diff / 60)
    return hours * 60 if 2 <= hours <= 12 else None
